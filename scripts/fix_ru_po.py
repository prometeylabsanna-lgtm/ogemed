def main() -> None:
    po = polib.pofile(str(PO_PATH))
    changed = 0
    for entry in po:
        mid = entry.msgid
        if mid in TRANSLATIONS:
            new = TRANSLATIONS[mid]
            if entry.msgstr != new or entry.fuzzy:
                entry.msgstr = new
                entry.flags = [f for f in entry.flags if f != "fuzzy"]
                changed += 1
        elif entry.fuzzy and entry.msgstr:
            # Drop fuzzy only when we have an explicit fix; leave others listed
            pass

    po.save()
    empty = [e.msgid for e in po if e.msgid and not e.msgstr]
    fuzzy = [e.msgid for e in po if e.fuzzy]
    print(f"updated={changed} empty={len(empty)} fuzzy={len(fuzzy)}")
    for e in empty[:30]:
        print(" EMPTY:", repr(e)[:100])
    for e in fuzzy[:20]:
        print(" FUZZY:", repr(e)[:100])


if __name__ == "__main__":
    main()
